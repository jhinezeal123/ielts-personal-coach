<#
.SYNOPSIS
  IELTS Coach auto-updater. Checks the latest GitHub release and fast-forwards
  the local git checkout to it.

.DESCRIPTION
  - Reads the local version from app/version.js (window.IELTS_VERSION = "x.y.z").
  - Calls https://api.github.com/repos/jhinezeal123/ielts-personal-coach/releases/latest
  - If the release tag (vX.Y.Z) is newer and the working tree is clean:
      git fetch origin --tags ; git merge --ff-only <tag>
    Never forces, never resets, never pushes.
  - Appends to scripts/auto-update.log and writes app/update-status.js
    (window.IELTS_UPDATE_STATUS = {...}) for the app to display.
  - Then runs scripts/sync-content.ps1 (lesson packs, content channel) regardless of
    the release result; a sync failure never affects the release flow.
  - Always exits 0 (safe for the Scheduled Task).

  Windows PowerShell 5.1 compatible. ASCII-only source.

.PARAMETER DryRun
  Only report what would happen (log + console). No git changes, no status file.
  -WhatIf is accepted as an alias of -DryRun.
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param(
    [switch]$DryRun
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$Repo       = 'jhinezeal123/ielts-personal-coach'
$ApiUrl     = "https://api.github.com/repos/$Repo/releases/latest"
$RepoRoot   = Split-Path -Parent $PSScriptRoot
$LogFile    = Join-Path $PSScriptRoot 'auto-update.log'
$VersionJs  = Join-Path $RepoRoot 'app\version.js'
$StatusJs   = Join-Path $RepoRoot 'app\update-status.js'
$IsDry      = [bool]($DryRun -or $WhatIfPreference)
# -WhatIf must not suppress our own log/status writes; we handle dry-run ourselves.
$WhatIfPreference = $false

function Write-Log {
    param([string]$Message, [string]$Level = 'INFO')
    $prefix = ''
    if ($IsDry) { $prefix = '[dry-run] ' }
    $line = '{0} [{1}] {2}{3}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Level, $prefix, $Message
    Write-Host $line
    try {
        [System.IO.File]::AppendAllText($LogFile, $line + [Environment]::NewLine, (New-Object System.Text.UTF8Encoding($false)))
    } catch { }
}

function Get-LocalVersion {
    if (-not (Test-Path -LiteralPath $VersionJs)) { return $null }
    $text = [System.IO.File]::ReadAllText($VersionJs)
    $m = [regex]::Match($text, 'IELTS_VERSION\s*=\s*["'']([^"'']+)["'']')
    if ($m.Success) { return $m.Groups[1].Value.Trim() }
    return $null
}

function ConvertTo-SemVer {
    param([string]$Value)
    if ([string]::IsNullOrWhiteSpace($Value)) { return $null }
    $m = [regex]::Match($Value.Trim(), '^[vV]?(\d+)(?:\.(\d+))?(?:\.(\d+))?')
    if (-not $m.Success) { return $null }
    $parts = @()
    foreach ($i in 1..3) {
        if ($m.Groups[$i].Success) { $parts += [int]$m.Groups[$i].Value } else { $parts += 0 }
    }
    return New-Object System.Version($parts[0], $parts[1], $parts[2])
}

function Write-Status {
    param(
        [string]$Result,
        [string]$Message,
        [string]$LocalVersion,
        [string]$LatestVersion,
        [string]$Path = $StatusJs
    )
    if ($IsDry) { return }
    $obj = [ordered]@{
        checkedAt     = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
        localVersion  = $LocalVersion
        latestVersion = $LatestVersion
        result        = $Result
        message       = $Message
    }
    $json = ConvertTo-Json -InputObject $obj -Compress
    $content = "/* Generated by scripts/auto-update.ps1 - do not edit, not tracked by git. */`r`nwindow.IELTS_UPDATE_STATUS = $json;`r`n"
    try {
        [System.IO.File]::WriteAllText($Path, $content, (New-Object System.Text.UTF8Encoding($false)))
    } catch {
        Write-Log ("Could not write status file: " + $_.Exception.Message) 'WARN'
    }
}

function Invoke-Git {
    # Returns @{ Code = <int>; Output = <string> }. Never throws on git stderr output.
    param([string[]]$GitArgs)
    $old = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $out = & git -C $RepoRoot @GitArgs 2>&1 | ForEach-Object { "$_" }
        $code = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $old
    }
    return @{ Code = $code; Output = (($out | Out-String).Trim()) }
}

function Invoke-Main {
    Write-Log "Check started (repo root: $RepoRoot)"

    $local = Get-LocalVersion
    if (-not $local) {
        Write-Log "Cannot read local version from $VersionJs" 'ERROR'
        Write-Status -Result 'error' -Message 'Cannot read app/version.js' -LocalVersion '' -LatestVersion ''
        return
    }
    $localV = ConvertTo-SemVer $local

    # --- Ask GitHub for the latest release -------------------------------
    try {
        [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
    } catch { }
    $headers = @{ 'User-Agent' = 'IELTS-Coach-AutoUpdate'; 'Accept' = 'application/vnd.github+json' }
    $release = $null
    try {
        $release = Invoke-RestMethod -Uri $ApiUrl -Headers $headers -Method Get -TimeoutSec 30 -UseBasicParsing
    } catch {
        $code = $null
        try { $code = [int]$_.Exception.Response.StatusCode } catch { }
        if ($code -eq 404) {
            Write-Log "No GitHub release published yet (404). Local version $local."
            Write-Status -Result 'no-release' -Message 'No release published on GitHub yet.' -LocalVersion $local -LatestVersion ''
        } else {
            $msg = $_.Exception.Message
            Write-Log "GitHub API request failed: $msg" 'WARN'
            Write-Status -Result 'error' -Message ("GitHub API request failed: " + $msg) -LocalVersion $local -LatestVersion ''
        }
        return
    }

    $tag = [string]$release.tag_name
    $remoteV = ConvertTo-SemVer $tag
    if (-not $remoteV -or -not $localV) {
        Write-Log "Unparsable version (local '$local', release tag '$tag')." 'WARN'
        Write-Status -Result 'error' -Message "Unparsable version (local '$local', tag '$tag')." -LocalVersion $local -LatestVersion $tag
        return
    }
    $latest = $tag -replace '^[vV]', ''

    if ($remoteV -le $localV) {
        Write-Log "Up to date (local $local, latest release $tag)."
        Write-Status -Result 'up-to-date' -Message "Local $local, latest release $tag." -LocalVersion $local -LatestVersion $latest
        return
    }

    Write-Log "New release available: $tag (local $local)."

    # --- Safety checks -----------------------------------------------------
    if (-not (Get-Command git -ErrorAction SilentlyContinue)) {
        Write-Log 'git is not installed or not on PATH; cannot update.' 'ERROR'
        Write-Status -Result 'error' -Message "Release $tag available but git was not found." -LocalVersion $local -LatestVersion $latest
        return
    }
    $st = Invoke-Git @('status', '--porcelain')
    if ($st.Code -ne 0) {
        Write-Log ("git status failed: " + $st.Output) 'ERROR'
        Write-Status -Result 'error' -Message 'git status failed.' -LocalVersion $local -LatestVersion $latest
        return
    }
    if ($st.Output) {
        Write-Log ("Working tree has uncommitted changes; NOT updating. Commit or stash them first:`r`n" + $st.Output) 'WARN'
        Write-Status -Result 'skipped-dirty' -Message "Release $tag available, but the folder has uncommitted changes. Nothing was changed." -LocalVersion $local -LatestVersion $latest
        return
    }
    $br = Invoke-Git @('symbolic-ref', '--quiet', '--short', 'HEAD')
    if ($br.Code -ne 0 -or -not $br.Output) {
        Write-Log 'HEAD is detached (not on a branch); NOT updating.' 'WARN'
        Write-Status -Result 'error' -Message "Release $tag available, but HEAD is detached." -LocalVersion $local -LatestVersion $latest
        return
    }
    $branch = $br.Output

    if ($IsDry) {
        Write-Log "Would run: git fetch origin --tags ; git merge --ff-only $tag (branch $branch). Dry run: nothing changed."
        return
    }

    # --- Fetch + fast-forward ---------------------------------------------
    $f = Invoke-Git @('fetch', 'origin', '--tags')
    if ($f.Code -ne 0) {
        Write-Log ("git fetch failed: " + $f.Output) 'WARN'
        Write-Status -Result 'error' -Message "git fetch failed while updating to $tag." -LocalVersion $local -LatestVersion $latest
        return
    }
    $ref = "refs/tags/$tag"
    $chk = Invoke-Git @('rev-parse', '--verify', '--quiet', "$ref^{commit}")
    if ($chk.Code -ne 0) {
        Write-Log "Tag $tag not found after fetch." 'WARN'
        Write-Status -Result 'error' -Message "Tag $tag not found after fetch." -LocalVersion $local -LatestVersion $latest
        return
    }
    $anc = Invoke-Git @('merge-base', '--is-ancestor', 'HEAD', $ref)
    if ($anc.Code -ne 0) {
        Write-Log "Branch $branch cannot be fast-forwarded to $tag (local history diverged). NOT updating; resolve manually." 'WARN'
        Write-Status -Result 'error' -Message "Cannot fast-forward $branch to $tag (history diverged). Nothing was changed." -LocalVersion $local -LatestVersion $latest
        return
    }
    $m = Invoke-Git @('merge', '--ff-only', $ref)
    if ($m.Code -ne 0) {
        Write-Log ("git merge --ff-only failed: " + $m.Output) 'WARN'
        Write-Status -Result 'error' -Message "Fast-forward to $tag failed. Nothing was forced." -LocalVersion $local -LatestVersion $latest
        return
    }
    $now = Get-LocalVersion
    if (-not $now) { $now = $latest }
    Write-Log "Updated $branch to $tag (version $local -> $now). Reload the app page."
    Write-Status -Result 'updated' -Message "Updated from $local to $now. Reload the page." -LocalVersion $now -LatestVersion $latest
}

# Allow dot-sourcing for tests without running.
if ($MyInvocation.InvocationName -ne '.') {
    try {
        Invoke-Main
    } catch {
        Write-Log ("Unexpected error: " + $_.Exception.Message) 'ERROR'
        try { Write-Status -Result 'error' -Message ("Unexpected error: " + $_.Exception.Message) -LocalVersion (Get-LocalVersion) -LatestVersion '' } catch { }
    }
    # Content channel (lesson packs): runs after the release check whatever its result.
    # A sync failure must never break the release flow (sync-content.ps1 also catches everything itself).
    try {
        $sync = Join-Path $PSScriptRoot 'sync-content.ps1'
        if (Test-Path -LiteralPath $sync) {
            if ($IsDry) { & $sync -DryRun } else { & $sync }
        } else {
            Write-Log 'sync-content.ps1 not found; content sync skipped.' 'WARN'
        }
    } catch {
        Write-Log ("Content sync failed: " + $_.Exception.Message) 'WARN'
    }
    exit 0
}
